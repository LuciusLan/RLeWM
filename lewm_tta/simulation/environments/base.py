"""Small contract for future PushT, Reacher, Two-Room and Cube adapters."""

from dataclasses import dataclass, field
from typing import Protocol
import numpy as np


@dataclass
class Observation:
    rgb: np.ndarray
    state: np.ndarray
    metrics: dict
    terminated: bool = False
    truncated: bool = False
    fields: dict = field(default_factory=dict)


class Environment(Protocol):
    @staticmethod
    def validate_config(settings: dict, planning: dict) -> None: ...
    def reset(self, case: dict, seed: int, *, history_start: bool) -> Observation: ...
    def step(self, raw_action: np.ndarray, *, recorded: bool = False) -> Observation: ...
    def reconstruction(self, observation: Observation, row: int) -> dict: ...
    def description(self) -> dict: ...
    def close(self) -> None: ...


class CollectionEnvironment(Protocol):
    @staticmethod
    def validate_collection_config(config: dict) -> None: ...
    @staticmethod
    def validate_collection_policy(config: dict) -> None: ...
    @staticmethod
    def validate_shift(shift: dict) -> None: ...
    @staticmethod
    def collection_schema() -> dict: ...
    @staticmethod
    def goal_diagnostics(state: np.ndarray, goal: np.ndarray, shift: dict) -> dict: ...
    def reset(self, seed: int) -> Observation: ...
    def step(self, action: np.ndarray) -> Observation: ...
    def collection_action(self, observation: Observation, rng, step: int, settings: dict) -> np.ndarray: ...
    def begin_collection(self, policy: dict) -> None: ...
    def collection_measurement(self) -> dict: ...
    def description(self) -> dict: ...
    def close(self) -> None: ...
